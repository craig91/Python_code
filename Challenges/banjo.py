def are_you_playing_banjo(name):
    if (name[0] == "R" or name[0] == "r"):
        return name + " plays banjo"
    else:
        return name + " does not play banjo"
    return name


are_you_playing_banjo("craig")
are_you_playing_banjo("ririri")
are_you_playing_banjo("Rikku")
are_you_playing_banjo("Minami")
are_you_playing_banjo("Adam")
are_you_playing_banjo("Ringo")